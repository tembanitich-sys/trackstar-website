// Generates public/api/lib/phone_data.php from libphonenumber-js metadata, so the PHP
// phone check follows the same rules as the site used before. Run: node scripts/gen-phone-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const meta = require("libphonenumber-js/metadata.min.json");

// Country names come from the static list the forms use.
const names = {};
for (const m of readFileSync("lib/country-data.ts", "utf8").matchAll(/\["([A-Z0-9]{2})","((?:[^"\\]|\\.)*)","\+(\d+)"\]/g)) names[m[1]] = JSON.parse(`"${m[2]}"`);

const php = (v) => {
  if (v === null || v === undefined || v === 0) return "null";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return `[${v.map(php).join(",")}]`;
  if (typeof v === "object") return `[${Object.entries(v).map(([k, x]) => `${php(String(k))}=>${php(x)}`).join(",")}]`;
  return `'${String(v).replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
};

const countries = {};
for (const [code, e] of Object.entries(meta.countries)) {
  if (!names[code]) throw new Error(`no name for ${code}`);
  // Number-type patterns exist only for a few countries (shared calling codes); any matching type is valid.
  const types = e[11]?.length ? e[11].filter(Boolean).map((t) => [t[0], t[1] ?? null]) : null;
  countries[code] = {
    name: names[code],
    cc: e[0],
    idd: e[1] || null,
    pattern: e[2],
    lengths: e[3] ?? null,
    prefix: e[5] || null,
    prefix_parse: e[7] || e[5] || null,
    transform: e[8] || null,
    leading: e[10] || null,
    types,
  };
}

const out = `<?php
// GENERATED by scripts/gen-phone-data.mjs from libphonenumber-js (metadata.min.json). Do not edit by hand.
return [
  'calling_codes' => ${php(meta.country_calling_codes)},
  'countries' => [
${Object.entries(countries).map(([c, v]) => `    '${c}' => ${php(v)},`).join("\n")}
  ],
];
`;
if (out.includes("~")) throw new Error("pattern contains ~, pick another regex delimiter");
writeFileSync("public/api/lib/phone_data.php", out);
console.log(`phone_data.php: ${Object.keys(countries).length} countries, ${(out.length / 1024).toFixed(0)} KB`);
